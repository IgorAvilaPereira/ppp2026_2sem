package negocio;

public class JBL {
    private int ligada;
    private String cancao;
    private String potencia;
    private boolean luzes;
    private int volume;

    public int getLigada() {
        return ligada;
    }
    public void setLigada(int ligada) {
        this.ligada = ligada;
    }
    public String getCancao() {
        return cancao;
    }
    public void setCancao(String cancao) {
        this.cancao = cancao;
    }
    public String getPotencia() {
        return potencia;
    }
    public void setPotencia(String potencia) {
        this.potencia = potencia;
    }
    public boolean isLuzes() {
        return luzes;
    }
    public void setLuzes(boolean luzes) {
        this.luzes = luzes;
    }
    public int getVolume() {
        return volume;
    }
    public void setVolume(int volume) {
        this.volume = volume;
    }

    
    

}
